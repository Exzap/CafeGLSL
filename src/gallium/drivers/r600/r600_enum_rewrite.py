def do_enum_print(name, lines):
    max_no = 0
    len = 0
    last_bits = {}
    for line in lines.split("\n"):
        result = line.strip()
        parts = result.split("=")
        values = parts[1].strip().split(" ")
        # The actual values we care about!
        key = parts[0].strip()
        op = values[0].strip()
        proc = values[1].strip()

        key_int = None
        if sint(key) is None:
            for c in TgsiOpcodes:
                if c.name == key:
                    key_int = c.value
        else:
            key_int = sint(key)
        if key_int is None:
            print(f"Unknown key: {key}")
            os.exit(1)

        if key_int > max_no:
            max_no = key_int

        last_bits[key_int] = f"{{ {op}, {proc} }},"
        len += 1

    print(
        f"const struct r600_shader_tgsi_instruction {name}[{max(max_no + 1, len)}] = {{"
    )
    for idx in range(max(max_no + 1, len)):
        if idx in last_bits:
            print("  " + last_bits[idx])
        else:
            print("  { 0, tgsi_unsupported },")
    print("};")


